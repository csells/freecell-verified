"""Generate Examples/Ms32000/*.lean from solve_range.py results.

Untrusted glue: every encoded move list is re-checked by `checkWin` inside Lean
(`checkDealChunk`), so a wrong or missing solution makes the build fail, not lie.

Usage: python3 tests/tools/gen_bulk.py OUTDIR RESULTS.jsonl [RESULTS.jsonl ...]
Later files override earlier ones for the same deal.
"""
import json, os, sys

LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz'
RANKS, SUITS = 'A23456789TJQK', 'CDHS'
LO, HI, CHUNK, UNWINNABLE = 1, 32000, 1000, 11982

def card_letter(name):
    rank = RANKS.index(name[:-1] if name[:-1] != '10' else 'T') + 1
    return LETTERS[(rank - 1) * 4 + SUITS.index(name[-1])]

def encode(move):
    src, dst = move.split()
    s = src[1:] if src.startswith('c') else card_letter(src[2:])
    d = {'h': 'h', 'f': 'f'}.get(dst) or dst[1:]
    assert len(s) == 1 and len(d) == 1, move
    return s + d

out_dir, files = sys.argv[1], sys.argv[2:]
sol = {}
for path in files:
    for line in open(path):
        r = json.loads(line)
        o = r['output']
        if o.get('result') == 'winnable':
            sol[r['deal']] = ''.join(encode(m) for m in o['moves'])
missing = [g for g in range(LO, HI + 1) if g not in sol and g != UNWINNABLE]
if missing:
    sys.exit(f'{len(missing)} deals lack a winning move list, e.g. {missing[:20]}')

os.makedirs(out_dir, exist_ok=True)
names = []
for k, lo in enumerate(range(LO, HI + 1, CHUNK), 1):
    hi = min(lo + CHUNK - 1, HI)
    name = f'Chunk{k:02d}'
    names.append((name, lo, hi))
    lines = [sol.get(g, '') for g in range(lo, hi + 1)]
    skip = [UNWINNABLE] if lo <= UNWINNABLE <= hi else []
    data = '\\n'.join(lines)
    text = f'''import FreeCell.Bulk

/-! Generated by `tests/tools/gen_bulk.py`; do not edit. Winning move lists for
Microsoft deals {lo}–{hi}, checked by `checkWin` through `native_decide`. -/

namespace FreeCell.Examples.Ms32000

def data{k:02d} : String := "{data}"

theorem chunk{k:02d} : ∀ n, {lo} ≤ n → n < {lo} + {hi - lo + 1} → n ∉ ({skip} : List Nat) →
    ∃ t, Reachable (msDeal n) t ∧ t.Won :=
  checkDealChunk_sound (data := data{k:02d}) (by native_decide)

end FreeCell.Examples.Ms32000
'''
    with open(os.path.join(out_dir, name + '.lean'), 'w') as f:
        f.write(text)

total = sum(len(s) // 2 for s in sol.values())
print(f'{len(names)} chunks, {len(sol)} deals, {total} moves', file=sys.stderr)

# The headline theorem: every deal 1..32000 is decided.
cases = []
for k, (name, lo, hi) in enumerate(names, 1):
    tail = 'exact' if k == len(names) else None
    if k < len(names):
        cases.append(f'    by_cases c{k} : n < {hi + 1}\n'
                     f'    · exact chunk{k:02d} n (by omega) (by omega) (by simp [hne])')
    else:
        cases.append(f'    exact chunk{k:02d} n (by omega) (by omega) (by simp [hne])')
imports = '\n'.join(['import FreeCell'] + [f'import Examples.Ms32000.{name}' for name, _, _ in names])
body = '\n'.join(cases)
open(os.path.join(out_dir, '..', 'Ms32000.lean'), 'w').write(f'''{imports}

/-!
# Every Microsoft deal 1–32000

Generated by `tests/tools/gen_bulk.py`; do not edit. Deal #11982 is unwinnable by the
complete search (`winnable_iff`); every other deal has a winning move list in
`Examples/Ms32000/Chunk*.lean`, checked by `checkWin`. Both evaluations use `native_decide`.
-/

namespace FreeCell.Examples.Ms32000

theorem deal11982_unwinnable : ¬ ∃ t, Reachable (msDeal 11982) t ∧ t.Won :=
  fun h => absurd ((winnable_iff _ (msDeal_valid 11982)).mpr h) (by native_decide)

/-- Of Microsoft deals 1–32000, exactly #11982 cannot be won. -/
theorem ms32000_winnable_iff (n : Nat) (h1 : 1 ≤ n) (h2 : n ≤ {HI}) :
    (∃ t, Reachable (msDeal n) t ∧ t.Won) ↔ n ≠ {UNWINNABLE} := by
  constructor
  · rintro hw rfl
    exact deal11982_unwinnable hw
  · intro hne
{body}

end FreeCell.Examples.Ms32000

#print axioms FreeCell.Examples.Ms32000.ms32000_winnable_iff
''')
